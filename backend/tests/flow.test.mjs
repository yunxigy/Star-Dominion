import test from 'node:test';
import assert from 'node:assert/strict';
import net from 'node:net';
import { once } from 'node:events';
import { mkdtempSync, readFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createBackend } from '../server.mjs';

test('real TCP + HTTP: registration, calibration, take/return, idempotency, persistence and offline', async t => {
  let now = 1000;
  const dir = mkdtempSync(path.join(os.tmpdir(), 'water-cabinet-'));
  const files = { calibrationFile: path.join(dir, 'calibration.json'), sessionFile: path.join(dir, 'sessions.json') };
  const backend = createBackend({ tcpPort: 0, httpPort: 0, host: '127.0.0.1', clock: () => now, adminToken: 'test-admin', ...files });
  const ports = await backend.listen();
  t.after(() => backend.close());
  const url = `http://127.0.0.1:${ports.httpPort}`;
  const request = async (route, data, token) => {
    const r = await fetch(url + route, data ? { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Admin-Token': token || '' }, body: JSON.stringify(data) } : {});
    return { status: r.status, ...await r.json() };
  };
  const socket = net.connect(ports.tcpPort, '127.0.0.1'); await once(socket, 'connect'); socket.setNoDelay(true);
  let received = ''; socket.on('data', chunk => { received += chunk; });
  const send = async line => { socket.write(line); await new Promise(r => setTimeout(r, 15)); };
  const stable = async grams => { for (let i = 0; i < 6; i++) { now += 250; await send(`RAW:${8000000 + grams * 100}\n`); } };
  const status = id => request(`/api/status?deviceId=CABINET001${id ? `&sessionId=${id}` : ''}`);
  await send('REG:CABI'); await send('NET001\r\nSTATUS:LOCKED\r\n');
  await stable(5500);
  assert.equal((await status()).calibrated, false);
  const input = { deviceId: 'CABINET001', rawEmpty: 8000000, rawLoaded: 8100000, knownGrams: 1000, bottleGrams: 550 };
  assert.equal((await request('/api/calibration', input)).status, 403);
  assert.equal((await request('/api/calibration', input, 'test-admin')).code, 0);
  assert.equal(JSON.parse(readFileSync(files.calibrationFile)).CABINET001.countsPerGram, 100);
  await stable(5500); await send('REG:CABINET001\n');
  assert.equal((await status()).doorStatus, 'LOCKED');
  assert.equal((await status()).weight, 5500);
  const payload = { deviceId: 'CABINET001', requestId: 'request-0001' };
  const opened = await request('/api/unlock', payload);
  assert.equal(opened.code, 0);
  assert.equal(opened.session.phase, 'UNLOCKING');
  const same = await request('/api/unlock', payload); assert.equal(same.sessionId, opened.sessionId);
  const recovered = await request('/api/status?deviceId=CABINET001&requestId=request-0001');
  assert.equal(recovered.session.id, opened.sessionId);
  assert.equal((await request('/api/unlock', { ...payload, requestId: 'different-0002' })).status, 409);
  assert.equal((await status()).session, null);
  assert.equal((received.match(/OPEN\n/g) || []).length, 1);
  await send('OK\n'); assert.equal((await status(opened.sessionId)).doorStatus, 'LOCKED');
  assert.equal((await request('/api/calibration', input, 'test-admin')).status, 409);
  await send('STATUS:OPEN\n'); await stable(4400);
  assert.equal((await status(opened.sessionId)).session.quantity, 2);
  await stable(4950); assert.equal((await status(opened.sessionId)).session.quantity, 1);
  await send('STATUS:LOCKED\n');
  assert.equal((await status(opened.sessionId)).session.phase, 'SETTLING');
  await stable(4950);
  const final = await status(opened.sessionId);
  assert.equal(final.session.phase, 'COMPLETED'); assert.equal(final.session.quantity, 1);
  assert.equal(JSON.parse(readFileSync(files.sessionFile)).CABINET001[0].quantity, 1);
  await send('WEIGHT:999999\n'); assert.equal((await status()).sensorOk, false);
  socket.destroy(); await new Promise(r => setTimeout(r, 20));
  assert.equal((await status(opened.sessionId)).online, false);
  assert.equal((await status(opened.sessionId)).session.quantity, 1);
  const restored = createBackend({ ...files, tcpPort: 0, httpPort: 0, host: '127.0.0.1' });
  await restored.listen(); t.after(() => restored.close());
  assert.equal(restored.devices.get('CABINET001').snapshot(opened.sessionId).session.quantity, 1);
});

test('unregistered and oversized protocol input cannot become a device', async t => {
  const backend = createBackend({ tcpPort: 0, httpPort: 0, host: '127.0.0.1', sessionFile: null, calibrationFile: null });
  const ports = await backend.listen(); t.after(() => backend.close());
  const socket = net.connect(ports.tcpPort, '127.0.0.1'); await once(socket, 'connect');
  socket.write('STATUS:OPEN\n'); await new Promise(r => setTimeout(r, 20));
  assert.equal(backend.devices.size, 0);
  const closed = once(socket, 'close'); socket.write('X'.repeat(300)); await closed;
  assert.equal(backend.devices.size, 0);
});
